#!/usr/bin/env node
// DOC-11: fails the build when a documented path no longer exists, so a rename orphans a
// paragraph in CLAUDE.md the same way it would orphan a broken import — instead of silently.
//
// Scope, deliberately narrow: root CLAUDE.md, every nested `**/CLAUDE.md`, `docs/architecture/**`
// and `CONTRIBUTING.md` — the docs an agent is expected to trust and act on. It does not check
// docs/reviews, docs/history or docs/superpowers, which are historical/working notes where a
// stale path is expected and already disclaimed.
//
// Method: pull every backtick code span out of those files, and inside each span look for tokens
// that look like a repo path — something with a `/` in it, or a bare filename ending in one of a
// known set of extensions. A path containing a placeholder character (`<`, `>`, `*`) is skipped —
// those are prose conventions (`<config>/sessions/<pid>.json`, `latest-*.yml`), not real paths. A
// bare filename (no `/`) is resolved by searching the whole repo for a unique basename match,
// since several nested CLAUDE.md files refer to a file in their own directory by name only.
//
// No dependencies beyond Node's own `fs`/`path`, so this stays fast and has nothing to install.

import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = process.cwd()

const DOC_FILES = []
function collectDocs(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      collectDocs(full)
    } else if (entry.name === 'CLAUDE.md') {
      DOC_FILES.push(full)
    }
  }
}
collectDocs(ROOT)

function collectDir(dir) {
  if (!statSync(dir, { throwIfNoEntry: false })) return
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) collectDir(full)
    else if (entry.name.endsWith('.md')) DOC_FILES.push(full)
  }
}
collectDir(join(ROOT, 'docs', 'architecture'))
collectDir(join(ROOT, 'docs', 'adr'))

const contributing = join(ROOT, 'CONTRIBUTING.md')
if (statSync(contributing, { throwIfNoEntry: false })) DOC_FILES.push(contributing)

// Explicit allowlist: real prose conventions and generic example paths used in "how to run a
// single test" snippets, none of which are meant to resolve to an actual file.
const ALLOWLIST = new Set([
  'settings.json',
  'session-layout.json',
  'themes.json',
  'pets.json',
  '.apiarypet.json', // the extension of an exported pet file, not a repo file
  'apiary.db',
  'search.db',
  'tests/unit/x.test.ts',
  'tests/integration/x.test.ts',
  'tests/component/x.test.tsx',
  'tests/e2e/x.spec.ts',
  'x.test.ts',
  'x.test.tsx',
  'x.spec.ts',
  '.claude/projects', // ~/.claude/projects — a user home-directory path, not a repo path
  'Claude/Anthropic/', // fragment of the commit-msg hook's regex, not a path
  'commitlint/config-conventional', // an npm package specifier (`@commitlint/...`), not a path
  'latest-mac.yml', // generated by electron-builder at release time, not a repo file
  'latest-linux.yml',
  'latest-*.yml',
  'xterm/addon-serialize', // the npm package `@xterm/addon-serialize`, not a repo path
  // Brace-expansion shorthand (`e2e/{a,b,c}.spec.ts`) leaves a bare extension fragment behind
  // once the tokenizer splits on the unmatched `{`/`}`/`,` — not a real path on its own.
  '.spec.ts',
  '.test.ts',
  '.test.tsx',
])

const PATH_EXTENSIONS = 'ts|tsx|mjs|cjs|js|json|yml|css|md|sh|jsonc'
// A token with at least one path separator, or a bare name ending in a known extension (dots
// allowed inside the name itself, e.g. `commitlint.config.js`, `.stylelintrc.json`).
// No leading `\b` on the bare-filename alternative: a dotfile like `.stylelintrc.json` starts
// with a non-word character, so a word-boundary assertion there would never match and the leading
// dot would be dropped. Each match runs against an already-isolated backtick span, so a boundary
// at the very start adds nothing.
const TOKEN_RE = new RegExp(
  `(?:[\\w.-]+/)+[\\w.-]+|\\.?[\\w.-]*[\\w-]\\.(?:${PATH_EXTENSIONS})\\b`,
  'g',
)

// Build an index of every repo-relative file path once, for resolving bare filenames and
// truncated/prefix references (e.g. `unit/scanner` standing in for `tests/unit/scanner*.test.ts`).
const ALL_PATHS = []
const BASENAME_INDEX = new Map()
const SKIP_DIRS = new Set([
  'node_modules', '.git', '.worktrees', '.claude', '.agent-reports', '.superpowers',
  'out', 'test-results', 'release', 'coverage',
])
function indexRepo(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      indexRepo(full)
    } else {
      const rel = relative(ROOT, full)
      ALL_PATHS.push(rel)
      const list = BASENAME_INDEX.get(entry.name) ?? []
      list.push(rel)
      BASENAME_INDEX.set(entry.name, list)
    }
  }
}
indexRepo(ROOT)

function looksLikePlaceholder(token) {
  return /[<>*]/.test(token)
}

function exists(relPath) {
  return statSync(join(ROOT, relPath), { throwIfNoEntry: false }) !== undefined
}

// Resolves a slash-containing token against the repo root, then against a `src/`/`tests/` prefix
// (docs routinely drop those, e.g. `main/pty/promptPath.ts` for `src/main/pty/promptPath.ts`), and
// finally as a directory-or-basename *prefix* of a real path, for shorthand like `unit/scanner`
// standing in for every `tests/unit/scanner*.test.ts` file.
const PATH_PREFIXES = ['', 'src/', 'tests/', 'src/main/', 'src/renderer/', 'src/shared/', 'src/shared/theme/']

function resolvesAsPath(candidate) {
  const roots = PATH_PREFIXES.map((prefix) => `${prefix}${candidate}`)
  for (const root of roots) {
    if (exists(root)) return true
    const slash = root.lastIndexOf('/')
    const dir = root.slice(0, slash)
    const base = root.slice(slash + 1)
    for (const p of ALL_PATHS) {
      const pSlash = p.lastIndexOf('/')
      if (p.slice(0, pSlash) === dir && p.slice(pSlash + 1).startsWith(base)) return true
    }
  }
  return false
}

const failures = []

// ── Symbols ──────────────────────────────────────────────────────────────────────────────────────
// A backticked identifier in these docs (`tidyLayout`, `BUILTIN_PLUGINS`, `SessionCatalog`) is an
// instruction to an agent: "call this", "register here". When the symbol is renamed or deleted the
// sentence goes stale the same way a path does (`setLayout` outlived its removal by two releases), so
// such a span must name an identifier that still occurs in the code. Only identifier-shaped spans
// that cannot be an English word are checked: camelCase, PascalCase with two humps, or CONSTANT_CASE.
const CODE_DIRS = ['src', 'tests', 'scripts', 'eslint', '.github', '.husky', 'build']
const IDENTIFIERS = new Set()
function indexIdentifiers(dir) {
  if (!statSync(dir, { throwIfNoEntry: false })) return
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) { indexIdentifiers(full); continue }
    if (full === import.meta.filename) continue // this file names stale symbols in its comments
    if (!/\.(ts|tsx|mjs|cjs|js|json|yml|yaml|sh|css)$/.test(entry.name) && !/^[\w-]+$/.test(entry.name)) continue
    for (const id of readFileSync(full, 'utf8').match(/[A-Za-z_$][\w$]*/g) ?? []) IDENTIFIERS.add(id)
  }
}
for (const d of CODE_DIRS) indexIdentifiers(join(ROOT, d))
for (const f of readdirSync(ROOT)) if (/\.(json|ts|js|cjs|mjs|yml)$/.test(f)) {
  for (const id of readFileSync(join(ROOT, f), 'utf8').match(/[A-Za-z_$][\w$]*/g) ?? []) IDENTIFIERS.add(id)
}
const IDENTIFIER_SPAN = /^@?([A-Za-z_$][\w$]*)(?:\.([A-Za-z_$][\w$]*))*(?:\(\))?$/
function isCodeShaped(id) {
  return /[a-z][A-Z]/.test(id) || /^[A-Z][A-Z0-9]*_[A-Z0-9_]+$/.test(id) || /^[A-Z][a-z0-9]+[A-Z][A-Za-z0-9]*$/.test(id)
}
// Code-shaped words in these docs that are not repo identifiers: Electron/DOM/library APIs and
// product names. Shrink this list when a name stops appearing in the docs.
const SYMBOL_ALLOWLIST = new Set([
  'getBoundingClientRect', 'innerText', 'contentVisibility', 'backdropFilter', 'webContents', 'BrowserWindow',
  'ipcMain', 'ipcRenderer', 'contextBridge', 'useSyncExternalStore', 'useEffect', 'useLayoutEffect', 'useState',
  'useMemo', 'useCallback', 'useRef', 'React', 'ResizeObserver', 'requestAnimationFrame', 'localStorage',
  'sessionStorage', 'indexedDB', 'GitHub', 'GitLab', 'JavaScript', 'TypeScript', 'macOS', 'iOS', 'VSCode', 'LiquidGlass',
  'execFile', 'setInterval', 'setTimeout', 'NaN', 'npmRebuild', 'isPackaged', 'senderFrame', 'webPreferences',
])
// Stale symbols that docs still name, each with the ledger id that fixes it. May only shrink: an
// entry that no longer fails is reported, so it is removed with the fix.
const SYMBOL_DEBT = new Map([])
const symbolDebtSeen = new Set()

function checkSymbol(relFile, inner) {
  const m = IDENTIFIER_SPAN.exec(inner.trim())
  if (!m) return
  const ids = inner.trim().replace(/^@/, '').replace(/\(\)$/, '').split('.')
  for (const id of ids) {
    if (!isCodeShaped(id) || SYMBOL_ALLOWLIST.has(id) || IDENTIFIERS.has(id)) continue
    const key = `${relFile}:${id}`
    if (SYMBOL_DEBT.has(key)) { symbolDebtSeen.add(key); continue }
    failures.push(`${relFile}: \`${id}\` — no identifier with this name in the code (renamed or removed?)`)
  }
}

// ── Links ────────────────────────────────────────────────────────────────────────────────────────
// `[text](relative/path)` must point at a file that exists (markdownlint checks only #anchors).
function checkLinks(relFile, text) {
  for (const m of text.matchAll(/\]\(([^)\s]+)\)/g)) {
    const target = m[1].split('#')[0]
    if (target === '' || /^[a-z]+:/i.test(target)) continue
    const rel = relative(ROOT, join(ROOT, relFile, '..', decodeURIComponent(target)))
    if (!exists(rel)) failures.push(`${relFile}: link to \`${target}\` — no such file`)
  }
}

for (const file of DOC_FILES) {
  const text = readFileSync(file, 'utf8')
  const relFile = relative(ROOT, file)
  checkLinks(relFile, text)
  // Pull out backtick-delimited spans (single backticks; docs don't use fenced code for paths).
  const spans = text.match(/`[^`\n]+`/g) ?? []
  for (const span of spans) {
    const inner = span.slice(1, -1)
    // A span with a placeholder character describes a pattern (`<config>/sessions/<pid>.json`,
    // `latest-*.yml`), not a concrete path — skip the whole span rather than the substring that
    // happens to still look path-like once the placeholder segment is stripped out.
    if (looksLikePlaceholder(inner)) continue
    checkSymbol(relFile, inner)
    const tokens = inner.match(TOKEN_RE) ?? []
    for (const token of tokens) {
      const cleaned = token.replace(/[.,;:)]+$/, '')
      if (ALLOWLIST.has(cleaned) || looksLikePlaceholder(cleaned)) continue
      if (cleaned.includes('/')) {
        // Try repo-root-relative, relative to the doc's own directory, then the src/tests
        // prefixes and prefix-match handled by resolvesAsPath.
        const relFromDoc = relative(ROOT, join(ROOT, relFile, '..', cleaned))
        if (exists(relFromDoc) || resolvesAsPath(cleaned)) continue
        failures.push(`${relFile}: \`${cleaned}\` — no such path`)
      } else {
        // Bare filename with a known extension: must exist somewhere in the repo.
        const matches = BASENAME_INDEX.get(cleaned)
        if (!matches || matches.length === 0) {
          failures.push(`${relFile}: \`${cleaned}\` — no file with this name anywhere in the repo`)
        }
      }
    }
  }
}

for (const key of SYMBOL_DEBT.keys()) {
  if (!symbolDebtSeen.has(key)) failures.push(`scripts/check-doc-refs.mjs: SYMBOL_DEBT entry \`${key}\` no longer fails — remove it`)
}

if (failures.length > 0) {
  console.error(`check-doc-refs: ${failures.length} stale reference(s) (path, symbol or link):\n`)
  for (const f of failures) console.error(`  ${f}`)
  console.error('\nFix the doc, or add a real allowlist entry to scripts/check-doc-refs.mjs if the')
  console.error('path is a deliberate placeholder or a runtime-only path, not a repo file.')
  process.exit(1)
}

console.log(`check-doc-refs: checked ${DOC_FILES.length} doc file(s): every referenced path, symbol and link exists.`)
